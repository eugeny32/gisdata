<?php

declare(strict_types=1);

/**
 * Физические константы и преобразования времени для генератора искусственных
 * RINEX-файлов (GPS + ГЛОНАСС). Используются стандартные значения из
 * ICD-GPS-200 (для GPS) и ICD ГЛОНАСС (для ГЛОНАСС/ПЗ-90.11).
 */

const RGEN_C = 299792458.0; // скорость света, м/с
const RGEN_GPS_F1 = 1575.42e6; // GPS L1, Гц
const RGEN_GPS_F2 = 1227.60e6; // GPS L2, Гц
const RGEN_GLO_F1 = 1602.0e6;  // ГЛОНАСС G1, k=0 (центральная литера), Гц
const RGEN_GLO_F2 = 1246.0e6;  // ГЛОНАСС G2, k=0, Гц
// ГЛОНАСС — FDMA: у каждого спутника СВОЯ несущая f_k = f0 + k*df, k от -7
// до +6 (литера/канал, поле "freq_channel" эфемериды, см. GlonassNav.php).
// До этой правки генератор считал длину волны ОДНОЙ номинальной частотой
// (k=0) для ВСЕХ спутников ГЛОНАСС сразу — отклонение до 7*df (~0.25% на
// крайних литерах) накапливается на случайной целочисленной
// неоднозначности фазы (до ±500000 циклов) в десятки-сотни метров
// эквивалента, из-за чего RTKLIB не мог уверенно разрешить целочисленную
// неоднозначность для ГЛОНАСС (см. живой тест с rnx2rtkp — GPS-only база
// сходилась в Fix до миллиметров, смешанная GPS+ГЛОНАСС оставалась Float).
const RGEN_GLO_F1_STEP = 0.5625e6; // шаг по литере для G1, Гц (ИКД ГЛОНАСС)
const RGEN_GLO_F2_STEP = 0.4375e6; // шаг по литере для G2, Гц

// GPS: гравитационный параметр и угловая скорость Земли (WGS-84 / ICD-GPS-200)
const RGEN_GPS_MU = 3.986005e14;
const RGEN_GPS_OMEGA_E = 7.2921151467e-5;

// ГЛОНАСС: гравитационный параметр и угловая скорость Земли (ПЗ-90.11)
const RGEN_GLO_MU = 3.9860044e14;
const RGEN_GLO_OMEGA_E = 7.292115e-5;
const RGEN_GLO_J02 = 1082625.75e-9; // второй зональный гармонический коэффициент (J2)
const RGEN_GLO_AE = 6378136.0;      // экваториальный радиус Земли, м

// Разница GPS-time и UTC на текущий момент (секунды) — последняя добавленная
// секунда координации была 31.12.2016, новых не было; если МСЭ объявит новую
// високосную секунду, это число нужно поднять на 1.
const RGEN_GPS_UTC_LEAP_SECONDS = 18;

/**
 * UTC Unix-timestamp -> "гражданское" представление момента ПО ШКАЛЕ GPST
 * (т.е. тот же Unix-timestamp, но смещённый на разницу GPST-UTC = 18с).
 *
 * ИСТОРИЯ (туда-обратно, см. git log этого файла за подробностями):
 * 1) Введена и применена к меткам эпох в RinexObsWriter.php — живой тест
 *    RTKLIB (rnx2rtkp, single-point) показал: без неё высота решения
 *    уходит на десятки км и плывёт линейно по времени, с ней — сходится
 *    к истинным координатам (mm-уровень в режиме Fix между 2 станциями).
 * 2) Откатили — реальный прогон через TBC на файле С этим сдвигом дал
 *    "Опорный файл содержит некорректные данные... начальная точка
 *    слишком далеко".
 * 3) ПОВТОРНО включили — прогон через RTKLIB на файле БЕЗ сдвига (после
 *    отката #2) воспроизвёл ТОТ ЖЕ дрейф высоты на десятки км, что и в
 *    пункте (1) — то есть откат не был "безопасным", просто ломал то, что
 *    было физически верным. При этом TBC ПОСЛЕ отката тоже не заработал
 *    (другая формулировка той же по сути ошибки — "координаты базовой
 *    станции недостаточно близки к истинным"). Значит TBC-проблема
 *    отдельная от этого конкретного числа и не решается откатом — сдвиг
 *    оставлен включённым как объективно более корректный (подтверждён
 *    дважды), а проблему с TBC нужно искать в другом месте.
 * Орбитальные/часовые расчёты ВНУТРИ генератора (rgen_utc_to_gps_week_sow
 * ниже) сдвиг всё равно делают независимо от этой функции — это про
 * физику спутника, не про то, что написано в файле.
 */
function rgen_gpst_unix(int $unixUtc): int
{
    return $unixUtc + RGEN_GPS_UTC_LEAP_SECONDS;
}

/**
 * UTC Unix-timestamp -> [номер недели GPS, секунды недели GPS].
 * Эпоха GPS: 6 января 1980, 00:00:00 UTC.
 */
function rgen_utc_to_gps_week_sow(int $unixUtc): array
{
    $gpsEpoch = gmmktime(0, 0, 0, 1, 6, 1980);
    $gpsTime = $unixUtc - $gpsEpoch + RGEN_GPS_UTC_LEAP_SECONDS;
    $week = intdiv($gpsTime, 7 * 86400);
    $sow = $gpsTime - $week * 7 * 86400;
    return [$week, $sow];
}

/**
 * Читает числовое поле фиксированной ширины (19 символов) из строки записи
 * RINEX NAV, начиная с $offset, с заменой фортрановской 'D'-экспоненты на
 * 'E' (некоторые генераторы RINEX до сих пор пишут её в D-нотации).
 * Общая для GPS- и ГЛОНАСС-парсеров — поэтому здесь, а не в одном из них.
 */
function rgen_read_f(string $line, int $offset): float
{
    $chunk = substr($line, $offset, 19);
    $chunk = str_replace(['D', 'd'], 'E', trim($chunk));
    return $chunk === '' ? 0.0 : (float)$chunk;
}
